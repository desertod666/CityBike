'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
require('../web/decoder.js');
const {Cache,cards,LIMIT}=require('../web/can-live.js');
const schema=JSON.parse(fs.readFileSync(path.join(__dirname,'../web/decoder_reference.json')));
let now=0;const cache=new Cache(schema,()=>now);
const frame=(id,data,seq,epoch=1,boot='A1B2C3D4')=>({id,extended:true,rtr:false,dlc:data.length/2,data,seq,epoch,boot,t_us:seq*1000});
const device={boot:'A1B2C3D4',epoch:1,can:'running'};
assert(cache.ingest(frame('04F83401','EAFF0B103B',1)));
assert(cache.ingest(frame('04F83400','6C395D37616164',2)));
assert(cache.ingest(frame('02F83201','00000000041050BE',3)));
let snap=cache.snapshot(device,true),rows=cards(snap,schema);
assert.equal(rows.length,16);assert.equal(rows.filter(r=>r.observed).length,3);
const battery=rows.find(r=>r.id==='04F83401');
assert.equal(battery.fields.find(f=>f.name==='Ток батареи').value,'-0,22');
assert.equal(battery.fields.find(f=>f.name==='Напряжение батареи').value,'41,07');
assert.equal(battery.fields.find(f=>f.name.startsWith('Электрическая мощность')).unit,'Вт');
const motor=rows.find(r=>r.id==='02F83201').fields.find(f=>f.name==='Температура мотора');
assert.equal(motor.value,'—');assert.match(motor.note,/0xBE/);assert(!JSON.stringify(motor).includes('150'));
assert.equal(cache.ingest({...frame('04F83401','FFFF',4),dlc:5}),false);
assert.equal(cache.ingest({...frame('04F83401','EAFF0B103B',5),extended:false}),false);
assert.equal(cache.ingest(frame('04F83401','EAFF0B103B',1)),false);
assert(cache.ingest({...frame('04F83401','',6),rtr:true,dlc:5}));assert.equal(cards(cache.snapshot(device,true),schema).find(r=>r.id==='04F83401').fields.find(f=>f.name==='Напряжение батареи').value,'41,07');
now=6000;rows=cards(cache.snapshot(device,true),schema);assert(rows.find(r=>r.id==='04F83401').stale);
assert(cards(cache.snapshot(device,false),schema).every(r=>r.stale));
assert.equal(cache.snapshot({...device,boot:'FFFFFFFF'},true).frames.length,0);
assert.equal(cache.snapshot({...device,epoch:2},true).frames.length,0);
for(let i=0;i<100;i++)assert(cache.ingest(frame((0x11000000+i).toString(16),'00',10+i)));
snap=cache.snapshot(device,true);assert.equal(snap.frames.length,LIMIT);
assert(snap.frames.some(f=>f.id==='04F83401'));assert(snap.evicted_ids>0);
assert(!JSON.stringify(snap).includes('decoded'));assert(!JSON.stringify(snap).includes('Spard'));
assert(cache.ingest(frame('01F83100','EE020001',1,2)));
assert.equal(cache.snapshot({...device,epoch:2},true).frames.length,1);
assert.equal(cards(cache.snapshot({...device,epoch:2},true),schema).filter(r=>r.observed).length,1);
assert(cache.ingest(frame('04F83401','00000B103B',1,1,'11223344')));
assert.equal(cache.snapshot({boot:'11223344',epoch:1,can:'running'},true).frames.length,1);
assert(!cache.snapshot({boot:'11223344',epoch:1,can:'stopped'},true).stream_active);
console.log('PASS ESP CAN latest cache: all known cards, signed battery/power, raw unavailable motor value, staleness/offline, bounded unknown IDs, no adapter injection, boot/epoch isolation');
